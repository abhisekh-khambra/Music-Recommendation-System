"""Generates backend/src/main/resources/data_raga_additions.sql from database/raga_tagged_hindi_songs.json.

Every statement is idempotent (guarded by WHERE NOT EXISTS / raga IS NULL), so DataInitializer runs the
file on every startup and existing databases pick up new songs without being re-seeded.

    python database/generate_raga_additions.py
"""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SRC = ROOT / "database" / "raga_tagged_hindi_songs.json"
OUT = ROOT / "backend" / "src" / "main" / "resources" / "data_raga_additions.sql"


def q(s):
    return "'" + str(s).replace("'", "''") + "'"


def main():
    data = json.loads(SRC.read_text(encoding="utf-8"))
    lines = ["-- GENERATED by database/generate_raga_additions.py from database/raga_tagged_hindi_songs.json — do not edit.",
             "-- Hindi film songs whose raga attribution comes from a cited source (see the JSON for each source).",
             "-- Emotion/mood annotations are the developer's; popularity 50 is a neutral default, not measured.", ""]
    for s in data["songs"]:
        values = ", ".join([
            q(s["title"]), q(s["artist"]), q(s["film"]), q(s["genre"]), q("Hindi"),
            str(s["energy"]), str(s["valence"]), q(s["primaryEmotion"]),
            q(json.dumps(s["secondaryEmotions"])), q(json.dumps(s["moodTags"])), q(s["raga"]), "50"])
        lines.append("INSERT INTO tracks (title, artist, album, genre, language, energy_level, valence, primary_emotion, "
                     "secondary_emotions, mood_tags, raga, popularity)")
        lines.append(f"SELECT {values} FROM DUAL")
        lines.append(f"WHERE NOT EXISTS (SELECT 1 FROM tracks WHERE title = {q(s['title'])} AND album = {q(s['film'])});  "
                     f"-- source: {s['source']}")
        lines.append("")
    for u in data.get("updates", []):
        lines.append(f"UPDATE tracks SET raga = {q(u['raga'])} WHERE title = {q(u['title'])} AND artist = {q(u['artist'])} "
                     f"AND raga IS NULL;  -- source: {u['source']}")
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote {OUT} ({len(data['songs'])} songs, {len(data.get('updates', []))} updates)")


if __name__ == "__main__":
    main()
